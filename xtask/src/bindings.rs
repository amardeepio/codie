//! Generates TypeScript bindings for the desktop client.
//!
//! The bindings are derived from the same Rust types the wire format uses, so
//! the webview cannot drift from the protocol. Output goes to
//! `desktop-app/src/lib/bindings/` and is produced by running the ts-rs
//! `export_bindings` tests with `TS_RS_EXPORT_DIR` pointed at a staging
//! directory.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use walkdir::WalkDir;

const TARGET: &str = "desktop-app/src/lib/bindings";

const INDEX_HEADER: &str = "\
// Generated by `cargo xtask bindings`. Do not edit.
//
// JSON numbers are typed as `number`: ts-rs maps Rust's 64-bit integers to
// `bigint`, but `JSON.parse` always produces numbers, so the raw binding would
// not describe what the webview actually receives.
";

/// Writes or verifies the desktop TypeScript bindings.
pub(crate) fn run(root: &Path, args: &[String]) -> Result<bool> {
    let check = match args {
        [] => false,
        [flag] if flag == "--check" => true,
        other => bail!("usage: cargo xtask bindings [--check] (got {other:?})"),
    };

    let staging = staging_dir();
    if staging.exists() {
        fs::remove_dir_all(&staging).context("cannot clear the bindings staging directory")?;
    }
    fs::create_dir_all(&staging).context("cannot create the bindings staging directory")?;

    let output = Command::new(env!("CARGO"))
        .current_dir(root)
        .args([
            "test",
            "-q",
            "-p",
            "codie-core",
            "-p",
            "codie-protocol",
            "--features",
            "typescript",
            "export_bindings",
        ])
        .env("TS_RS_EXPORT_DIR", &staging)
        .env("CARGO_TERM_COLOR", "never")
        .output()
        .context("cannot run the ts-rs export tests")?;
    if !output.status.success() {
        bail!(
            "ts-rs export failed\n{}\n{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
    }

    let files = collect(&staging)?;
    if files.is_empty() {
        bail!("ts-rs produced no bindings");
    }
    let _ = fs::remove_dir_all(&staging);
    let target = root.join(TARGET);

    if check {
        compare(&target, &files)?;
        println!("ok: {} ({} files)", target.display(), files.len());
    } else {
        write_tree(&target, &files)?;
        println!("wrote {} ({} files)", target.display(), files.len());
    }
    Ok(true)
}

fn staging_dir() -> PathBuf {
    std::env::temp_dir().join(format!("codie-bindings-{}", std::process::id()))
}

fn collect(directory: &Path) -> Result<BTreeMap<String, Vec<u8>>> {
    let mut files = BTreeMap::new();

    for entry in WalkDir::new(directory).sort_by_file_name() {
        let entry = entry.context("cannot read the bindings staging directory")?;
        if !entry.file_type().is_file() {
            continue;
        }
        let path = entry.path();
        if path.extension().and_then(std::ffi::OsStr::to_str) != Some("ts") {
            continue;
        }
        let relative = path
            .strip_prefix(directory)
            .context("bindings escaped the staging directory")?;
        let relative = relative
            .components()
            .map(|component| component.as_os_str().to_string_lossy())
            .collect::<Vec<_>>()
            .join("/");
        let source =
            fs::read_to_string(path).with_context(|| format!("cannot read {}", path.display()))?;
        let normalized = source.replace("bigint", "number");
        files.insert(relative, normalized.into_bytes());
    }

    let index = render_index(files.keys());
    files.insert("index.ts".to_owned(), index.into_bytes());
    Ok(files)
}

fn render_index<'a>(modules: impl Iterator<Item = &'a String>) -> String {
    let mut output = String::from(INDEX_HEADER);
    output.push('\n');
    for module in modules {
        if module == "index.ts" {
            continue;
        }
        let stem = module.strip_suffix(".ts").unwrap_or(module);
        output.push_str(&format!("export type * from \"./{stem}\";\n"));
    }
    output
}

fn write_tree(target: &Path, files: &BTreeMap<String, Vec<u8>>) -> Result<()> {
    if target.exists() {
        fs::remove_dir_all(target).with_context(|| format!("cannot clear {}", target.display()))?;
    }
    for (relative, contents) in files {
        let path = target.join(relative);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("cannot create {}", parent.display()))?;
        }
        fs::write(&path, contents).with_context(|| format!("cannot write {}", path.display()))?;
    }
    Ok(())
}

fn compare(target: &Path, expected: &BTreeMap<String, Vec<u8>>) -> Result<()> {
    if !target.exists() {
        bail!(
            "{} is missing; run `cargo xtask bindings` to generate it",
            target.display()
        );
    }

    let mut differences = Vec::new();
    let actual = collect(target)?;
    for (relative, contents) in expected {
        match actual.get(relative) {
            Some(current) if current == contents => {}
            Some(_) => differences.push(format!("changed: {relative}")),
            None => differences.push(format!("missing: {relative}")),
        }
    }
    for relative in actual.keys() {
        if !expected.contains_key(relative) {
            differences.push(format!("unexpected: {relative}"));
        }
    }

    if differences.is_empty() {
        return Ok(());
    }
    bail!(
        "TypeScript bindings are out of date:\n{}\nrun `cargo xtask bindings` and commit the result",
        differences.join("\n")
    )
}
